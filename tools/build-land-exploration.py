'''Generate the coverage weights from the same terrain used for walking.'''
import base64
import json
import math
import struct
from itertools import groupby
from pathlib import Path

import numpy as np

root = Path(__file__).resolve().parents[1] / 'dist'
terrain = (root / 'assets/overland-terrain.bin').read_bytes()
signature, width, height = struct.unpack_from('<4sHH', terrain)
assert (signature, width, height) == (b'WWL1', 7200, 3600)
offsets = np.frombuffer(terrain, '<u4', height + 1, 8)
runs = np.frombuffer(terrain, '<u2', offset=8 + 4 * len(offsets))
walkable = np.zeros((height, width), dtype=np.uint8)
for y in range(height):
    x = 0
    for raw in runs[offsets[y]:offsets[y+1]]:
        end = int(raw) >> 3
        if raw & 7 == 1:
            walkable[y, x:end] = 1
        x = end
coverage = walkable.reshape(720, 5, 1440, 5).sum(axis=(1, 3)).astype(np.uint8)
mask = json.loads((root / 'exploration-mask.js').read_text(encoding='utf8').split('EXPLORATION_MASK=', 1)[1].strip().rstrip(';'))
sea_bits = np.unpackbits(np.frombuffer(base64.b64decode(mask['bits']), dtype=np.uint8), bitorder='little')
sea_grid = sea_bits.reshape(280, 720).repeat(2, axis=0).repeat(2, axis=1)

# The shared sea chart runs from 80 N to 60 S. The rest can still be walked.
overlap = np.zeros_like(coverage)
overlap[40:600] = sea_grid
area_per_walk_cell = [
    round(6371000**2 * math.radians(.25) *
          (math.sin(math.radians(90-y/4)) - math.sin(math.radians(90-(y+1)/4))) / 25)
    for y in range(720)
]
extra = sum(int(c) * area for c, area in zip(np.where(overlap, 0, coverage).sum(axis=1), area_per_walk_cell))

data = bytearray()
for value, group in groupby(coverage.flat):
    count = sum(1 for _ in group)
    while count:
        length = min(65535, count)
        if length <= 7:
            data.append(length << 5 | int(value))
        else:
            data.extend(struct.pack('<BH', int(value), length))
        count -= length

target = root / 'land-exploration-data.js'
text = '// Generated by tools/build-land-exploration.py.\n'
text += 'export const LAND_ADDITIONAL_AREA_M2='+str(extra)+';\n'
text += 'export const LAND_TILE_COUNT='+str(np.count_nonzero(coverage))+';\n'
text += 'export const LAND_COVERAGE_RUNS='+json.dumps(base64.b64encode(data).decode())+';\n'
target.write_text(text, encoding='utf8')
print(f'{np.count_nonzero(coverage):,} walkable tiles, {len(data):,} encoded bytes, {extra/1e6:,.0f} additional km²')
