import fs from 'node:fs';
const root=new URL('../',import.meta.url);
const data=JSON.parse(fs.readFileSync(new URL('tools/port-catalog.json',root),'utf8'));
if(Object.keys(data.economy).length!==88||Object.keys(data.goods).length!==24||data.ports.length!==24)throw Error('항구·상품 명세 개수 불일치');
for(const [id,p] of Object.entries(data.economy))for(const g of [...Object.keys(p.stock),...p.demand])if(!data.goods[g]||g==='spice')throw Error(`잘못된 상품 ${id}/${g}`);
const content='// Generated by tools/build-catalog.mjs from tools/port-catalog.json.\n'+Object.entries({GOODS:data.goods,PORT_ECONOMY:data.economy,NEW_PORT_IDS:data.ports.map(p=>p.id)}).map(([key,value])=>`export const ${key} = ${JSON.stringify(value,null,2)};`).join('\n')+'\n';
const target=new URL('dist/port-economy.js',root);
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8').replaceAll('\r\n','\n')!==content)throw Error('상품 생성물이 원본과 다릅니다.');}
else fs.writeFileSync(target,content);
